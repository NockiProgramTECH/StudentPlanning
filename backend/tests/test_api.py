def test_postgres_schema_and_placeholders_are_compatible():
    schema = _postgres_schema("""
        CREATE TABLE example (id INTEGER PRIMARY KEY AUTOINCREMENT, cost_usd REAL NOT NULL DEFAULT 0.0);
        CREATE INDEX idx_example_id ON example(id);
    """)
    assert len(schema) == 2
    assert "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in schema[0]
    assert "cost_usd DOUBLE PRECISION" in schema[0]
    assert _postgres_sql("SELECT * FROM example WHERE id = ? AND name = ?") == (
        "SELECT * FROM example WHERE id = %s AND name = %s"
    )


def test_database_url_initializes_empty_postgres_schema(monkeypatch):
    executed = []
    connection_args = {}

    class FakeConnection:
        def __enter__(self):
            return self

        def __exit__(self, *_args):
            return False

        def execute(self, query, params=()):
            executed.append((query, params))

    psycopg = ModuleType("psycopg")
    psycopg.connect = lambda url, row_factory: (
        connection_args.update(url=url, row_factory=row_factory) or FakeConnection()
    )
    rows = ModuleType("psycopg.rows")
    rows.dict_row = object()
    monkeypatch.setitem(sys.modules, "psycopg", psycopg)
    monkeypatch.setitem(sys.modules, "psycopg.rows", rows)
    monkeypatch.setenv("DATABASE_URL", "postgresql://user:pass@example.test/db?sslmode=require")

    CourseStore()

    statements = [query for query, _ in executed]
    assert connection_args["url"].startswith("postgresql://")
    assert "CREATE TABLE IF NOT EXISTS course_documents" in statements[0]
    assert any("course_usage" in statement for statement in statements)
    assert any("chariow_pulse_deliveries" in statement for statement in statements)
    assert all("AUTOINCREMENT" not in statement for statement in statements)


def test_app_startup_creates_empty_local_schema(tmp_path, monkeypatch):
    db_path = tmp_path / "empty.sqlite3"
    monkeypatch.delenv("DATABASE_URL", raising=False)
    monkeypatch.setenv("STUDIA_DB_PATH", str(db_path))
    with TestClient(app):
        with sqlite3.connect(db_path) as conn:
            tables = {
                row[0] for row in conn.execute(
                    "SELECT name FROM sqlite_master WHERE type = 'table'"
                )
            }
    assert {"course_documents", "course_questions", "chariow_licenses"} <= tables
    with sqlite3.connect(db_path) as conn:
        assert conn.execute("SELECT COUNT(*) FROM course_documents").fetchone()[0] == 0


